/** 写进【你的身份】的风格说明。 */
export function formatPersona(id: string): string {
  const p = DEBATER_PERSONAS[id];
  if (!p) return "";
  return `你的风格：「${p.title}」
- 论证习惯：${p.thinking}
- 语言风格：${p.voice}
- 招牌打法：${p.signature}只在最合适的地方用，不要每段都用。
- 注意避免：${p.avoid}
风格只影响你从哪里切入、怎么组织和表达，不改变你的立场、职责和引用规则；发言中不要自称或提及这个风格。`;
}
